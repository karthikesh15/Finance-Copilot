def t(lang, key, **kw):
    text = TEXTS.get(lang, TEXTS["en"]).get(key) or TEXTS["en"][key]
    return text.format(**kw) if kw else text


def cat_name(lang, category):
    return CATEGORIES_TXT.get(lang, CATEGORIES_TXT["en"]).get(category, (category, ""))[0]


def cat_label(lang, category):
    emoji = CATEGORY_CONFIG.get(category, ("", None))[0]
    return f"{emoji} {cat_name(lang, category)}".strip()


def category_prompt(lang):
    lines = [t(lang, "cat_header"), ""]
    for key, (emoji, _) in CATEGORY_CONFIG.items():
        name, desc = CATEGORIES_TXT[lang][key]
        lines.append(f"{emoji} {name} → {desc}")
    return "\n".join(lines)
